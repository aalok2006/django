function buildProject(
  base: Omit<InfrastructureProject, 'prediction' | 'acquisitionProgressPct'>
): InfrastructureProject {
  const acquisitionProgressPct = Math.round(
    (base.acquiredAreaHectares / Math.max(1, base.totalAreaHectares)) * 100
  );
  const prediction = predictProjectDelay(base.features);
  return {
    ...base,
    acquisitionProgressPct,
    prediction,
  };
}

